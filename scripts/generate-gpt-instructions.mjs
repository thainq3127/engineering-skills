import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = process.cwd();
const manifestPath = "gpts/manifest.json";

const normalize = (text) => text.replaceAll("\r\n", "\n").trimEnd() + "\n";

const read = (relativePath) =>
  normalize(fs.readFileSync(path.join(root, relativePath), "utf8"));

const relativeToGpts = (relativePath) => path.join("gpts", relativePath);

const parseManifest = () => {
  const manifest = JSON.parse(read(manifestPath));
  if (!Number.isInteger(manifest.contractVersion) || manifest.contractVersion < 1) {
    throw new Error(`${manifestPath}: contractVersion must be a positive integer`);
  }
  if (!Array.isArray(manifest.agents) || manifest.agents.length === 0) {
    throw new Error(`${manifestPath}: agents must be a non-empty array`);
  }
  return manifest;
};

const validateAgent = (agent, seenIds, seenOutputs) => {
  for (const field of ["id", "displayName", "description", "role", "output"]) {
    if (typeof agent[field] !== "string" || agent[field].trim() === "") {
      throw new Error(`${manifestPath}: agent is missing ${field}`);
    }
  }
  if (!Array.isArray(agent.shared) || agent.shared.length === 0) {
    throw new Error(`${manifestPath}: ${agent.id} must declare shared sources`);
  }
  if (!Array.isArray(agent.canonicalSkills) || agent.canonicalSkills.length === 0) {
    throw new Error(`${manifestPath}: ${agent.id} must declare canonicalSkills`);
  }
  if (seenIds.has(agent.id)) {
    throw new Error(`${manifestPath}: duplicate agent id ${agent.id}`);
  }
  if (seenOutputs.has(agent.output)) {
    throw new Error(`${manifestPath}: duplicate output ${agent.output}`);
  }
  seenIds.add(agent.id);
  seenOutputs.add(agent.output);

  const sourcePaths = [...agent.shared, agent.role].map(relativeToGpts);
  for (const sourcePath of sourcePaths) {
    if (!fs.existsSync(path.join(root, sourcePath))) {
      throw new Error(`${manifestPath}: ${agent.id} source does not exist: ${sourcePath}`);
    }
  }
  for (const skillPath of agent.canonicalSkills) {
    if (!fs.existsSync(path.join(root, skillPath))) {
      throw new Error(`${manifestPath}: ${agent.id} canonical skill does not exist: ${skillPath}`);
    }
  }
  if (!agent.output.startsWith("generated/") || !agent.output.endsWith(".instructions.md")) {
    throw new Error(`${manifestPath}: ${agent.id} output must be generated/*.instructions.md`);
  }
};

const sourceDigest = (manifest, agent, sources) => {
  const payload = JSON.stringify({
    contractVersion: manifest.contractVersion,
    agent,
    sources,
  });
  return crypto.createHash("sha256").update(payload).digest("hex").slice(0, 16);
};

const renderAgent = (manifest, agent) => {
  const sourcePaths = [...agent.shared, agent.role].map(relativeToGpts);
  const sources = sourcePaths.map((sourcePath) => ({
    path: sourcePath,
    content: read(sourcePath),
  }));
  const digest = sourceDigest(manifest, agent, sources);
  const canonicalSkills = agent.canonicalSkills.map((skill) => `- \`${skill}\``).join("\n");
  const composedSources = sources
    .map(({ path: sourcePath, content }) => `<!-- source: ${sourcePath} -->\n\n${content.trimEnd()}`)
    .join("\n\n");

  return normalize(`# ${agent.displayName} GPT contract

Contract ID: \`${agent.id}\`
Contract version: \`${manifest.contractVersion}\`
Source digest: \`${digest}\`

${agent.description}

This file is generated by \`scripts/generate-gpt-instructions.mjs\`. Do not edit it directly.

## Canonical maintenance sources

${canonicalSkills}

${composedSources}
`);
};

export const buildGeneratedInstructions = () => {
  const manifest = parseManifest();
  const seenIds = new Set();
  const seenOutputs = new Set();
  const outputs = new Map();

  for (const agent of manifest.agents) {
    validateAgent(agent, seenIds, seenOutputs);
    outputs.set(relativeToGpts(agent.output), renderAgent(manifest, agent));
  }

  return { manifest, outputs };
};

export const checkGeneratedInstructions = () => {
  const errors = [];
  let generated;
  try {
    generated = buildGeneratedInstructions();
  } catch (error) {
    return [error.message];
  }

  for (const [outputPath, expected] of generated.outputs) {
    const absolutePath = path.join(root, outputPath);
    if (!fs.existsSync(absolutePath)) {
      errors.push(`${outputPath}: missing generated GPT instructions`);
      continue;
    }
    const actual = normalize(fs.readFileSync(absolutePath, "utf8"));
    if (actual !== expected) {
      errors.push(`${outputPath}: generated GPT instructions are stale; run npm run generate:gpts`);
    }
  }
  return errors;
};

const writeOutputs = () => {
  const { outputs } = buildGeneratedInstructions();
  for (const [outputPath, content] of outputs) {
    const absolutePath = path.join(root, outputPath);
    fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
    fs.writeFileSync(absolutePath, content);
    console.log(`Generated ${outputPath}`);
  }
};

const printPatch = () => {
  const { outputs } = buildGeneratedInstructions();
  console.log("*** Begin Patch");
  for (const [outputPath, content] of outputs) {
    const absolutePath = path.join(root, outputPath);
    if (fs.existsSync(absolutePath)) {
      console.log(`*** Update File: ${outputPath}`);
      console.log("@@");
      for (const line of normalize(fs.readFileSync(absolutePath, "utf8")).split("\n").slice(0, -1)) {
        console.log(`-${line}`);
      }
      for (const line of content.split("\n").slice(0, -1)) {
        console.log(`+${line}`);
      }
    } else {
      console.log(`*** Add File: ${outputPath}`);
      for (const line of content.split("\n").slice(0, -1)) {
        console.log(`+${line}`);
      }
    }
  }
  console.log("*** End Patch");
};

const main = () => {
  if (process.argv.includes("--check")) {
    const errors = checkGeneratedInstructions();
    if (errors.length > 0) {
      console.error(errors.map((error) => `ERROR: ${error}`).join("\n"));
      process.exit(1);
    }
    console.log("Generated GPT instructions are current.");
    return;
  }
  if (process.argv.includes("--patch")) {
    printPatch();
    return;
  }
  writeOutputs();
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
